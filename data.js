// Root-position triads (root in octave 3).
const TRIADS = { C: ['C3', 'E3', 'G3'], Dm: ['D3', 'F3', 'A3'], Em: ['E3', 'G3', 'B3'], F: ['F3', 'A3', 'C4'], G: ['G3', 'B3', 'D4'], Am: ['A3', 'C4', 'E4'] };
const chordNotes = (name) => TRIADS[name];
const bassOf = (name) => name[0] + '2';

// Left-hand events for chords [name, start, length] in 4/4:
// 'block' = triad held for the whole chord, 'beats' = triad on every beat, 'bass' = bass on beats 1 and 3, triad on 2 and 4,
const accompany = (chords, pattern) => chords.flatMap(([name, start, len]) => {
  let ev;
  if (pattern === 'block') ev = [{ notes: chordNotes(name), start, b: len }];
  else {
    ev = Array.from({ length: len }, (_, i) => {
      const t = start + i;
      return { notes: pattern === 'bass' && t % 2 === 0 ? [bassOf(name)] : chordNotes(name), start: t, b: 0.9 };
    });
  }
  ev.forEach((e, i) => { e.hand = 'L'; e.chord = i === 0 ? name : null; });
  return ev;
});

// Events of the whole song, or of one section. hand: 'R' | 'L'.
// easy: the video-based sections with the chosen left-hand pattern; orig: the sheet, played in its form order.
const easyEvents = (s, pattern) => [
  ...s.easy.map(([n, start, b], i) => ({ hand: 'R', notes: [n], start, b, section: i === 0 ? s.name : null })),
  ...accompany(s.chords, pattern),
];
const sheetEvents = (part, offset) => part.bars.flatMap((n, k) => {
  const { chords, rh, lh } = SONG.sheet.bars[n], t = offset + k * 4;
  const names = chords.split(' '), chordAt = (st) => (names.length === 1 ? (st === 0 ? names[0] : null) : names[[0, 2].indexOf(st)] ?? null);
  return [
    ...rh.map(([note, st, b], i) => ({ hand: 'R', notes: [note], start: t + st, b, section: k === 0 && i === 0 ? part.name : null })),
    ...lh.map(([notes, st, b]) => ({ hand: 'L', notes: notes.split(' '), start: t + st, b, chord: chordAt(st) })),
  ];
});
const songEvents = (section, level = 'easy', pattern = 'block') => {
  let ev;
  if (level === 'easy') ev = SONG.sections.filter((s) => !section || s.name === section).flatMap((s) => easyEvents(s, pattern));
  else {
    let offset = 0;
    ev = SONG.sheet.form.flatMap((part) => {
      const out = !section || part.name === section ? sheetEvents(part, offset) : [];
      offset += part.bars.length * 4;
      return out;
    });
  }
  ev.sort((x, y) => x.start - y.start);
  // re-time by whole bars so beat 1 stays beat 1
  const t0 = ev.length ? Math.floor(Math.min(...ev.map((e) => e.start)) / 4) * 4 : 0;
  ev.forEach((e) => { e.start = Math.round((e.start - t0) * 1000) / 1000; });
  return ev;
};

// Group the chosen hands' events that start together (within 0.15 beat) into steps the player must hit.
const practiceSteps = (events, hands) => {
  const steps = [];
  for (const e of events) {
    if (!hands.includes(e.hand)) continue;
    const s = steps.at(-1);
    if (s && e.start - s.start < 0.15) s.events.push(e);
    else steps.push({ start: e.start, events: [e] });
  }
  return steps;
};

