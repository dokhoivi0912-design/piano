const NAMES = ['C', 'C#', 'D', 'D#', 'E', 'F', 'F#', 'G', 'G#', 'A', 'A#', 'B'];
const SOLFEGE = { C: 'Đô', D: 'Rê', E: 'Mi', F: 'Fa', G: 'Sol', A: 'La', B: 'Si' };
const solfege = (n) => SOLFEGE[n[0]] + (n.includes('#') ? '#' : '');
const noteToMidi = (n) => NAMES.indexOf(n.slice(0, -1)) + 12 * (Number(n.slice(-1)) + 1);
const midiToNote = (m) => NAMES[m % 12] + (Math.floor(m / 12) - 1);
const noteToFreq = (n) => 440 * 2 ** ((noteToMidi(n) - 69) / 12);
const samePitchClass = (a, b) => noteToMidi(a) % 12 === noteToMidi(b) % 12;

// Song notes keep the video's real pitch; the computer keyboard plays them folded into its range.
const KEY_LO = noteToMidi('G4'), KEY_HI = noteToMidi('C6');
const fitToKeys = (n) => {
  let m = noteToMidi(n);
  while (m < KEY_LO) m += 12;
  while (m > KEY_HI) m -= 12;
  return midiToNote(m);
};

