// Root-position triads (root in octave 3).
const TRIADS = { C: ['C3', 'E3', 'G3'], Dm: ['D3', 'F3', 'A3'], Em: ['E3', 'G3', 'B3'], F: ['F3', 'A3', 'C4'], G: ['G3', 'B3', 'D4'], Am: ['A3', 'C4', 'E4'] };
const chordNotes = (name) => TRIADS[name];
const bassOf = (name) => name[0] + '2';

// Left-hand events for chords [name, start, length] in 4/4:
// 'block' = triad held for the whole chord, 'beats' = triad on every beat, 'bass' = bass on beats 1 and 3, triad on 2 and 4.
const accompany = (chords, pattern) => chords.flatMap(([name, start, len]) => {
  const ev = pattern === 'block'
    ? [{ notes: chordNotes(name), start, b: len }]
    : Array.from({ length: len }, (_, i) => {
      const t = start + i;
      return { notes: pattern === 'bass' && t % 2 === 0 ? [bassOf(name)] : chordNotes(name), start: t, b: 0.9 };
    });
  ev.forEach((e, i) => { e.hand = 'L'; e.chord = i === 0 ? name : null; });
  return ev;
});

// Events of the whole song, or of one section. hand: 'R' | 'L'.
// level 'easy' builds the left hand from the chords with the chosen pattern; 'orig' is the video arrangement.
const songEvents = (section, level = 'easy', pattern = 'block') => {
  const secs = (level === 'easy' ? SONG.easy.sections : SONG.sections).filter((s) => !section || s.name === section);
  const ev = secs.flatMap((s) => {
    const lh = level === 'easy' ? accompany(s.chords, pattern) : s.lh.map(([notes, start, b]) => ({ hand: 'L', notes: notes.split(' '), start, b }));
    const rh = s.rh.map(([notes, start, b], i) => ({ hand: 'R', notes: notes.split(' '), start, b, section: i === 0 ? s.name : null }));
    return [...rh, ...lh];
  }).sort((x, y) => x.start - y.start);
  // re-time to start at 0; the easy grid moves by whole bars so beat 1 stays beat 1
  let t0 = ev.length ? Math.min(...ev.map((e) => e.start)) : 0;
  if (level === 'easy') t0 = Math.floor(t0 / 4) * 4;
  ev.forEach((e) => { e.start = Math.round((e.start - t0) * 100) / 100; });
  return ev;
};

// Group the chosen hands' events that start together (within 0.15 beat) into steps the player must hit.
const practiceSteps = (events, hands) => {
  const steps = [];
  for (const e of events) {
    if (!hands.includes(e.hand)) continue;
    const s = steps.at(-1);
    if (s && e.start - s.start < 0.15) s.events.push(e);
    else steps.push({ start: e.start, events: [e] });
  }
  return steps;
};

// What counts as "the same key": real pitch folded to the computer keys, or (MIDI) any octave of the note.
const matchKey = (n, input) => (input === 'midi' ? NAMES[noteToMidi(n) % 12] : fitToKeys(n));

