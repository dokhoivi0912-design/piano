// Pass a section name to get one section; omit for the whole song.
const songNotes = (section) => {
  let start = 0;
  return SONG.sections
    .filter((s) => !section || s.name === section)
    .flatMap((s) => s.notes.map(([n, b], i) => {
      const x = { n, b, start, section: i === 0 ? s.name : null };
      start += b;
      return x;
    }));
};

